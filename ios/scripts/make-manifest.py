#!/usr/bin/env python3
"""Writes PhononCore/Sources/PhononCore/ModelManifest+Pinned.swift from a local copy of the
pinned model files (hf download --revision <sha> --local-dir ...). Each file is hashed here,
so the app checks every byte it downloads against this list."""
import hashlib, os, sys
models = sys.argv[1]
out = sys.argv[2]
ASR_REPO, ASR_REV = "FluidInference/parakeet-tdt-0.6b-v2-coreml", "ee09c569f73759e6d44c9bd16766f477b2b36d39"
REF_REPO, REF_REV = "Infatoshi/phonon-refiner-1.7b", "2b0ab74bee7ab7cf364695bbe44f64ce4c47439e"
ASR_ITEMS = ["Preprocessor.mlmodelc", "Encoder.mlmodelc", "Decoder.mlmodelc", "JointDecision.mlmodelc", "parakeet_vocab.json"]
REF_ITEMS = ["phonon-refiner-1.7b-Q4_K_S-e4.gguf"]
def files(base, items):
    for item in items:
        p = os.path.join(base, item)
        if os.path.isdir(p):
            for d, _, fs in sorted(os.walk(p)):
                for f in sorted(fs):
                    yield os.path.relpath(os.path.join(d, f), base)
        else:
            yield item
def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()
def entries(base, repo, rev, items, folder):
    rows = []
    for rel in files(base, items):
        p = os.path.join(base, rel)
        rows.append(f'        .init(repo: "{repo}", revision: "{rev}", path: "{rel}", folder: "{folder}", size: {os.path.getsize(p)}, sha256: "{sha(p)}"),')
    return rows
asr = entries(os.path.join(models, "parakeet-tdt-0.6b-v2-coreml"), ASR_REPO, ASR_REV, ASR_ITEMS, "parakeet-tdt-0.6b-v2-coreml")
ref = entries(os.path.join(models, "phonon-refiner-1.7b"), REF_REPO, REF_REV, REF_ITEMS, "phonon-refiner-1.7b")
with open(out, "w") as fh:
    fh.write("// Generated by ios/scripts/make-manifest.py. Do not edit by hand.\n\n")
    fh.write("extension ModelManifest {\n")
    fh.write("    public static let asrFiles: [ModelFile] = [\n" + "\n".join(asr) + "\n    ]\n\n")
    fh.write("    public static let refinerFiles: [ModelFile] = [\n" + "\n".join(ref) + "\n    ]\n}\n")
print(len(asr), "asr files,", len(ref), "refiner files")
